#!/usr/bin/env python3
"""Small, stdlib-only deployment CLI. Never sources .env as shell code."""
import argparse
import datetime
import getpass
import json
import os
from pathlib import Path
import re
import secrets
import shutil
import socket
import subprocess
import sys
import tempfile
import urllib.parse

ROOT = Path(__file__).resolve().parent
ENV = ROOT / '.env'
KEY = re.compile(r'^[A-Z][A-Z0-9_]*$')
MANAGED = {'mongo', 'redis', 'es'}


def read_env(path=None):
    path = ENV if path is None else path
    values = {}
    for line in path.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        key, sep, value = line.partition('=')
        if not sep or not KEY.fullmatch(key):
            raise ValueError('Invalid .env entry (expected KEY=value)')
        if value.startswith("'") and value.endswith("'"):
            value = value[1:-1].replace("\\'", "'")
        values[key] = value
    return values


def write_env(path, values):
    content = '# Managed by setup.sh / settings.sh. Keep private; never commit.\n'
    for key, value in values.items():
        if not KEY.fullmatch(key) or '\n' in value or '\r' in value or '\x00' in value:
            raise ValueError('Invalid configuration key/value')
        content += key + "='" + value.replace("'", "\\'") + "'\n"
    atomic_write(path, content)


def atomic_write(path, content):
    fd, name = tempfile.mkstemp(prefix='.' + path.name + '-', dir=path.parent)
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, 'w') as stream:
            stream.write(content)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def compose(*args, env_path=None, check=True, env=None):
    env_path = ENV if env_path is None else env_path
    # Ambient shell variables must not silently replace deployment secrets/settings.
    child = os.environ.copy()
    if env_path.exists():
        for key in read_env(env_path):
            child.pop(key, None)
    child.update(env or {})
    return subprocess.run(['docker', 'compose', '--env-file', str(env_path), '-f',
                           str(ROOT / 'compose.yaml'), *args], cwd=ROOT, env=child, check=check)


def require_docker():
    if sys.platform != 'linux':
        raise ValueError('Run deployment on a Linux Docker host (host networking is required).')
    subprocess.run(['docker', 'info', '--format', '{{.ServerVersion}}'], check=True,
                   stdout=subprocess.DEVNULL)
    subprocess.run(['docker', 'compose', 'version'], check=True)


def ask(label, default='', secret=False):
    suffix = ' [configured]' if secret and default else (' [' + default + ']' if default else '')
    value = (getpass.getpass if secret else input)(label + suffix + ': ').strip()
    return value or default


def selected_services(values):
    return [name for name in ('mongo', 'redis', 'es') if values.get(name.upper() + '_MODE') == 'docker']


def validate(values):
    for key in ('API_PORT', 'WEB_PORT', 'GATEWAY_PORT', 'MONGO_PORT', 'REDIS_PORT', 'ES_PORT'):
        if not values.get(key, '').isdigit() or not 1 <= int(values[key]) <= 65535:
            raise ValueError('Invalid port: ' + key)
    ports = [values[key] for key in ('API_PORT', 'WEB_PORT', 'GATEWAY_PORT')]
    ports += [values[name.upper() + '_PORT'] for name in selected_services(values)]
    if len(ports) != len(set(ports)):
        raise ValueError('Service ports must be different')
    if values['GATEWAY_BIND'] not in ('127.0.0.1', '0.0.0.0'):
        raise ValueError('GATEWAY_BIND must be 127.0.0.1 or 0.0.0.0')
    if set(filter(None, values.get('COMPOSE_PROFILES', '').split(','))) != set(selected_services(values)):
        raise ValueError('Database modes and Compose profiles disagree; use setup for initial selection')
    for key in ('API_IMAGE', 'WEB_IMAGE'):
        if not re.fullmatch(r'[a-zA-Z0-9._/@:+-]+', values[key]):
            raise ValueError('Invalid image reference: ' + key)
    for key in ('MONGO_ROOT_PASSWORD', 'REDIS_PASSWORD', 'ELASTIC_PASSWORD'):
        if len(values.get(key, '')) < 16 or values[key] == 'SET_BY_SETUP':
            raise ValueError('Database password must be generated by setup: ' + key)


def setup(args):
    if ENV.exists() or (ROOT / 'config.yml').exists():
        raise ValueError('Configuration already exists; setup will not overwrite it. Use settings.sh.')
    require_docker()
    values = read_env(ROOT / '.env.example')
    for key in ('MONGO_ROOT_PASSWORD', 'REDIS_PASSWORD', 'ELASTIC_PASSWORD', 'MTV2_JWT_SECRET'):
        values[key] = secrets.token_hex(32)
    values['API_IMAGE'] = args.api_image or values['API_IMAGE']
    values['WEB_IMAGE'] = args.web_image or values['WEB_IMAGE']
    if args.reuse_all and not args.existing_config:
        raise ValueError('--reuse-all requires --existing-config')
    for name, label in (('mongo', 'MongoDB'), ('redis', 'Redis'), ('es', 'Elasticsearch')):
        mode = 'existing' if args.reuse_all else ask(label + ': 1=新建 Docker，2=已有宿主机/远程服务', '1')
        if mode not in ('1', '2', 'existing'):
            raise ValueError('Choose 1 or 2')
        values[name.upper() + '_MODE'] = 'docker' if mode == '1' else 'existing'
    values['COMPOSE_PROFILES'] = ','.join(selected_services(values))
    if not args.reuse_all:
        values['GATEWAY_BIND'] = ask('入口绑定地址', '0.0.0.0')
        values['GATEWAY_PORT'] = ask('入口端口', '80')
        values['API_PORT'] = ask('API 内部端口', '18080')
        values['WEB_PORT'] = ask('前端内部端口', '13000')
    else:
        values.update(GATEWAY_BIND='127.0.0.1', GATEWAY_PORT='18000')
        # Preserve all settings and JWT from the old YAML unless explicitly overridden later.
        for key in list(values):
            if key.startswith('MTV2_'):
                values.pop(key)
    if not args.reuse_all:
        configure_databases(values, bool(args.existing_config))
    validate(values)
    project = values['COMPOSE_PROJECT_NAME']
    for name in selected_services(values):
        volume = project + '_' + name + '_data'
        if subprocess.run(['docker', 'volume', 'inspect', volume], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode == 0:
            raise ValueError('Existing data volume found: ' + volume + '; setup will not adopt or initialize it')
    # Check fresh listeners before creating any containers.
    for key in ('GATEWAY_PORT', 'API_PORT', 'WEB_PORT'):
        port_available(values[key])
    for name in selected_services(values):
        port_available(values[name.upper() + '_PORT'])
    config = Path(args.existing_config).read_text() if args.existing_config else (ROOT / 'config.yml.example').read_text()
    # Keep the host directory private. The mounted YAML must be readable by UID
    # 10001 inside the API; .env and release history remain mode 0600.
    ROOT.chmod(0o700)
    (ROOT / 'certs').mkdir(exist_ok=True)
    atomic_write(ROOT / 'config.yml', config)
    (ROOT / 'config.yml').chmod(0o644)
    write_env(ENV, values)
    try:
        compose('config', '--quiet')
    except Exception:
        # Preserve private config for diagnosis; never create databases on validation failure.
        raise
    print('配置已保存。已有服务只做连接检查；只初始化本次选择由 Compose 管理的数据库。')
    if not args.prepare_only:
        deploy(argparse.Namespace(build=False, local=args.local, version=None))
        if not args.reuse_all and values['MONGO_MODE'] == 'docker' and ask('创建首个管理员？y/N', 'n').lower() == 'y':
            admin(None)


def configure_databases(values, has_yaml):
    if values['MONGO_MODE'] == 'docker':
        values['MONGO_PORT'] = ask('Docker MongoDB 本机端口', '27017')
        values['MTV2_MONGODB_URI'] = ('mongodb://mtv2_root:' + values['MONGO_ROOT_PASSWORD'] +
                                    '@127.0.0.1:' + values['MONGO_PORT'] + '/?authSource=admin')
    elif has_yaml:
        values.pop('MTV2_MONGODB_URI', None)
    else:
        values['MTV2_MONGODB_URI'] = ask('已有 MongoDB URI（含认证信息）', secret=True)
        if not values['MTV2_MONGODB_URI'].startswith(('mongodb://', 'mongodb+srv://')):
            raise ValueError('A MongoDB URI is required')
    if values['REDIS_MODE'] == 'docker':
        values['REDIS_PORT'] = ask('Docker Redis 本机端口', '6379')
        values.update(MTV2_REDIS_HOST='127.0.0.1', MTV2_REDIS_PORT=values['REDIS_PORT'], MTV2_REDIS_PASSWORD=values['REDIS_PASSWORD'])
    elif has_yaml:
        for key in ('MTV2_REDIS_HOST', 'MTV2_REDIS_PORT', 'MTV2_REDIS_PASSWORD'):
            values.pop(key, None)
    else:
        values['MTV2_REDIS_HOST'] = ask('已有 Redis 地址', '127.0.0.1')
        values['MTV2_REDIS_PORT'] = ask('已有 Redis 端口', '6379')
        values['MTV2_REDIS_PASSWORD'] = ask('已有 Redis 密码（可留空）', secret=True)
        values['MTV2_REDIS_DB'] = ask('已有 Redis DB', '0')
    if values['ES_MODE'] == 'docker':
        values['ES_PORT'] = ask('Docker ES 本机端口', '9200')
        values.update(MTV2_ES_HOSTS='http://127.0.0.1:' + values['ES_PORT'], MTV2_ES_USERNAME='elastic', MTV2_ES_PASSWORD=values['ELASTIC_PASSWORD'])
    elif has_yaml:
        for key in ('MTV2_ES_HOSTS', 'MTV2_ES_USERNAME', 'MTV2_ES_PASSWORD'):
            values.pop(key, None)
    else:
        values['MTV2_ES_HOSTS'] = ask('已有 ES URL（多个用逗号）', 'http://127.0.0.1:9200')
        values['MTV2_ES_USERNAME'] = ask('已有 ES 用户名（可留空）')
        values['MTV2_ES_PASSWORD'] = ask('已有 ES 密码（可留空）', secret=True)
    if values['ES_MODE'] == 'existing':
        ca = ask('已有 ES 的 CA 文件路径（HTTP 或公共 CA 可留空）')
        if ca:
            (ROOT / 'certs').mkdir(exist_ok=True)
            shutil.copyfile(ca, ROOT / 'certs' / 'es-ca.crt')
            (ROOT / 'certs' / 'es-ca.crt').chmod(0o644)
            values['MTV2_ES_CA_FILE'] = '/etc/mtv2/certs/es-ca.crt'
    values['MTV2_MONGODB_DATABASE'] = ask('网站 MongoDB 数据库名', 'mtv2') if not has_yaml else ask('MongoDB 数据库名覆盖（留空保留 YAML）')
    if not values['MTV2_MONGODB_DATABASE']:
        values.pop('MTV2_MONGODB_DATABASE')
    values['MTV2_ES_INDEX'] = ask('网站 ES 索引名', 'problems') if not has_yaml else ask('ES 索引名覆盖（留空保留 YAML）')
    if not values['MTV2_ES_INDEX']:
        values.pop('MTV2_ES_INDEX')
    if has_yaml:
        values.pop('MTV2_JWT_SECRET', None)


def port_available(port):
    with socket.socket() as sock:
        try:
            sock.bind(('0.0.0.0', int(port)))
        except OSError:
            raise ValueError('Port already in use: ' + port + '; choose another port or an existing service')


def initialize_managed(values):
    # A marker is written only after successful initialization. An existing-service
    # selection never reaches these operations, even if the underlying DB is empty.
    for service in ('mongo', 'es'):
        marker = ROOT / ('.initialized-' + service)
        if service in selected_services(values) and not marker.exists():
            command = 'init-mongo' if service == 'mongo' else 'init-es'
            compose('run', '--rm', '--no-deps', 'api', '/app/mtv2ctl', command)
            atomic_write(marker, 'Initialized ' + datetime.datetime.now(datetime.timezone.utc).isoformat() + '\n')


def apply(local=False, build=False, initialize=False):
    values = read_env()
    validate(values)
    compose('config', '--quiet')
    if build:
        compose('build', 'api', 'web')
    elif not local:
        compose('pull', 'api', 'web', 'gateway')
    services = selected_services(values)
    if services:
        compose('up', '-d', '--no-recreate', '--wait', '--wait-timeout', '300', *services)
    compose('run', '--rm', '--no-deps', 'api', '/app/mtv2ctl', 'check-config')
    if initialize:
        initialize_managed(values)
    compose('up', '-d', '--force-recreate', '--no-build', '--wait', '--wait-timeout', '180', 'api', 'web', 'gateway')


def deploy(args):
    require_docker()
    values = read_env()
    if args.version:
        if not re.fullmatch(r'[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}', args.version):
            raise ValueError('Invalid version tag')
        for key in ('API_IMAGE', 'WEB_IMAGE'):
            image = values[key].split('@')[0]
            last = image.rsplit('/', 1)[-1]
            if ':' in last:
                image = image.rsplit(':', 1)[0]
            values[key] = image + ':' + args.version
    previous = ENV.read_text()
    # Save only a successfully deployed release as a rollback candidate.
    deployed = ROOT / '.deployed.env'
    rollback = ROOT / '.rollback.env'
    write_env(ENV, values)
    try:
        apply(local=args.local, build=args.build, initialize=True)
    except Exception:
        atomic_write(ENV, previous)
        print('部署失败，原配置已恢复；数据库和卷保留。已有成功版本可执行 rollback。', file=sys.stderr)
        raise
    if deployed.exists() and deployed.read_text() != ENV.read_text():
        atomic_write(rollback, deployed.read_text())
    atomic_write(deployed, ENV.read_text())
    compose('ps')
    print('部署健康检查通过；入口端口 ' + values['GATEWAY_PORT'])


def settings(args):
    values = read_env()
    key = args.key or ask('修改设置名称，例如 GATEWAY_PORT、MTV2_DEEPSEEK_KEY')
    allowed = set(read_env(ROOT / '.env.example')) | {
        'MTV2_MONGODB_DATABASE', 'MTV2_REDIS_DB', 'MTV2_ES_INDEX', 'MTV2_ALLOWED_ORIGINS',
        'MTV2_DEEPSEEK_KEY', 'MTV2_DEEPSEEK_BASE_URL', 'MTV2_DEEPSEEK_MODEL',
        'MTV2_OPENROUTER_KEY', 'MTV2_OPENROUTER_BASE_URL', 'MTV2_OPENROUTER_MODEL',
        'MTV2_PROBLEMS_QUEUE', 'MTV2_DAILY_QUEUE', 'MTV2_ES_INSECURE_SKIP_VERIFY',
        'MTV2_ES_CA_FILE',
    }
    immutable = {'COMPOSE_PROFILES', 'COMPOSE_PROJECT_NAME', 'MONGO_ROOT_PASSWORD', 'REDIS_PASSWORD',
                 'ELASTIC_PASSWORD', 'MONGO_IMAGE', 'REDIS_IMAGE', 'ES_IMAGE', 'MONGO_PORT', 'REDIS_PORT', 'ES_PORT'}
    if key not in allowed or key in immutable:
        raise ValueError('This setting changes database identity/storage and requires a planned migration; not changed')
    secret = any(word in key for word in ('PASSWORD', 'SECRET', '_KEY', '_URI'))
    value = args.value if args.value is not None else ask(key, values.get(key, ''), secret=secret)
    values[key] = value
    validate(values)
    previous = ENV.read_text()
    atomic_write(ROOT / '.settings-backup.env', previous)
    write_env(ENV, values)
    try:
        # --no-deps and explicit services ensure settings never recreate databases.
        compose('config', '--quiet')
        compose('run', '--rm', '--no-deps', 'api', '/app/mtv2ctl', 'check-config')
        compose('up', '-d', '--force-recreate', '--no-build', '--no-deps', '--wait', '--wait-timeout', '180', 'api', 'web', 'gateway')
    except Exception:
        atomic_write(ENV, previous)
        compose('up', '-d', '--no-build', '--no-deps', '--wait', '--wait-timeout', '180', 'api', 'web', 'gateway', check=False)
        raise
    atomic_write(ROOT / '.deployed.env', ENV.read_text())
    print('设置已应用；数据库容器未更新。')


def rollback(_):
    saved = ROOT / '.rollback.env'
    if not saved.exists():
        raise ValueError('No previous successful release recorded')
    before = ENV.read_text()
    atomic_write(ENV, saved.read_text())
    try:
        # No initialization or database recreation during a rollback.
        compose('up', '-d', '--no-build', '--no-deps', '--wait', '--wait-timeout', '180', 'api', 'web', 'gateway')
    except Exception:
        atomic_write(ENV, before)
        raise
    atomic_write(saved, before)
    atomic_write(ROOT / '.deployed.env', ENV.read_text())


def admin(_):
    username = ask('管理员用户名')
    email = ask('管理员邮箱')
    password = getpass.getpass('管理员密码（12–72 字节）: ')
    if password != getpass.getpass('再次输入密码: '):
        raise ValueError('Passwords do not match')
    compose('run', '--rm', '--no-deps', '-e', 'MTV2_ADMIN_USERNAME', '-e', 'MTV2_ADMIN_EMAIL',
            '-e', 'MTV2_ADMIN_PASSWORD', 'api', '/app/mtv2ctl', 'admin',
            env={'MTV2_ADMIN_USERNAME': username, 'MTV2_ADMIN_EMAIL': email, 'MTV2_ADMIN_PASSWORD': password})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    p = sub.add_parser('setup')
    p.add_argument('--existing-config')
    p.add_argument('--reuse-all', action='store_true')
    p.add_argument('--prepare-only', action='store_true')
    p.add_argument('--local', action='store_true', help='use application images already loaded on this host')
    p.add_argument('--api-image')
    p.add_argument('--web-image')
    p.set_defaults(run=setup)
    p = sub.add_parser('deploy')
    p.add_argument('version', nargs='?')
    p.add_argument('--build', action='store_true')
    p.add_argument('--local', action='store_true', help='use already loaded application images')
    p.set_defaults(run=deploy)
    p = sub.add_parser('settings')
    p.add_argument('key', nargs='?')
    p.add_argument('value', nargs='?')
    p.set_defaults(run=settings)
    sub.add_parser('rollback').set_defaults(run=rollback)
    sub.add_parser('admin').set_defaults(run=admin)
    sub.add_parser('status').set_defaults(run=lambda _: compose('ps'))
    args = parser.parse_args()
    try:
        args.run(args)
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        # Commands contain setting names but never secret values. Connection errors
        # should be diagnosed from private container logs, not printed config dumps.
        print('Error: ' + str(error), file=sys.stderr)
        sys.exit(1)


if __name__ == '__main__':
    main()
